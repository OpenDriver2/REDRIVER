	VECTOR4 y;
	VECTOR4 z;

	z.vx = target->vx - camera_position.vx;
	z.vy = target->vy - camera_position.vy;
	z.vz = target->vz - camera_position.vz;

	Normalise(&z);

	camera_matrix.m[2][0] = z.vx;
