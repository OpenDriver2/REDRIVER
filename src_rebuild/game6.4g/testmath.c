// [0x52948b] [D]
void EulerToQuaternion(SVECTOR *rot, QUATERNION *quat)
{
	float sz;
	float cz;
	float sy;
	float cy;
	float sx;
	float cx;
	float sc;
	float ss;
	float cc;
	float cs;

	cx = fcos(rot->vx / 2);
	cy = fcos(rot->vy / 2);
	cz = fcos(rot->vz / 2);
	sx = fsin(rot->vx / 2);
	sy = fsin(rot->vy / 2);
	sz = fsin(rot->vz / 2);

	cc = cx * cz;
	cs = cx * sz;
	sc = sx * cz;
	ss = sx * sz;

	quat->v.vx = cy * sc - sy * cs;
	quat->v.vy = cy * ss + sy * cc;
	quat->v.vz = cy * cs - sy * sc;
	quat->s = cy * cc + sy * ss;

	NormQuaternion(quat);
}

// [0x529596] [D]
// The rotation by angle about a unit axis.
void MatrixFromAngleAndAxis(int angle, VECTOR4 *axis, MATRIX *mat)
{
	float y2;
	float z;
	float y;
	float x2;
	float yz;
	float snz;
	float sn;
	float omc;
	float z2;
	float xz;
	float sny;
	float xy;
	float snx;

	sn = fsin(angle);
	y = axis->vy;
	z = axis->vz;
	omc = 1.0f - fcos(angle);

	x2 = axis->vx * axis->vx;
	y2 = y * y;
	z2 = z * z;
	xy = axis->vx * y;
	xz = axis->vx * z;
	yz = y * z;
	snx = sn * axis->vx;
	sny = sn * y;
	snz = sn * z;

	mat->m[0][0] = 1.0f - (y2 + z2) * omc;
	mat->m[0][1] = omc * xy + snz;
	mat->m[0][2] = omc * xz - sny;
	mat->m[1][0] = omc * xy - snz;
	mat->m[1][1] = 1.0f - (x2 + z2) * omc;
	mat->m[1][2] = omc * yz + snx;
	mat->m[2][0] = omc * xz + sny;
	mat->m[2][1] = omc * yz - snx;
	mat->m[2][2] = 1.0f - (x2 + y2) * omc;
}

