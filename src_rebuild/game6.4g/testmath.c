// [0x528e60] [D]
void UnitVector(VECTOR4 *in, VECTOR4 *out)
{
	float recip;
	float len;

	len = in->vx * in->vx + in->vy * in->vy + in->vz * in->vz;
	len = (float)sqrt(len);

	if (len == 0.0f)
	{
		out->vx = 0.0f;
		out->vy = 0.0f;
		out->vz = 0.0f;
	}
	else
	{
		recip = 1.0f / len;

		out->vx = recip * in->vx;
		out->vy = recip * in->vy;
		out->vz = recip * in->vz;
	}
}

