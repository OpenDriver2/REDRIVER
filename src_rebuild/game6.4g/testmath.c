	camera_matrix.m[2][2] = z.vz;

	y.vx = up->vx;
	y.vy = up->vy;
	y.vz = up->vz;

	x = *CrossProduct(&tmp2, &z, &y);
	Normalise(&x);

	camera_matrix.m[0][0] = x.vx;
	camera_matrix.m[0][1] = x.vy;
	camera_matrix.m[0][2] = x.vz;

