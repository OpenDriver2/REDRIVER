// [0x527cce] [D]
// The angle (4096 to a turn) of the vector (x, y) from the +y axis towards +x; Arctan_Table
// covers one octant.
int Arc_Tan(LONG y, LONG x)
{
	if (!x && !y)
		return 0;

	if (y < 0)
	{
		if (x <= 0)
		{
			if (-x <= -y)
				return 3072 - Arctan_Table[-(y / 2 + (x << 10)) / -y];
			else
				return Arctan_Table[-(x / 2 + (y << 10)) / -x] + 2048;
		}
		else if (x <= -y)
		{
			return Arctan_Table[((x << 10) - y / 2) / -y] + 3072;
		}
		else
		{
			return (4096 - Arctan_Table[(x / 2 - (y << 10)) / x]) & 0xFFF;
		}
	}
	else if (x <= 0)
	{
		if (-x <= y)
			return Arctan_Table[(y / 2 - (x << 10)) / y] + 1024;
		else
			return 2048 - Arctan_Table[((y << 10) - x / 2) / -x];
	}
	else if (x <= y)
	{
		return 1024 - Arctan_Table[((x << 10) + y / 2) / y];
	}
	else
	{
		return Arctan_Table[((y << 10) + x / 2) / x];
	}
}

