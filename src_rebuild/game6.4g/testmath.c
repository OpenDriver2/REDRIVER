{
	return a->vx * b->vx + a->vy * b->vy + a->vz * b->vz;
}

// [0x527ead] [D]
VECTOR4 *CrossProduct(VECTOR4 *out, VECTOR4 *a, VECTOR4 *b)
{
	VECTOR4 cp;

	cp.vx = a->vy * b->vz - a->vz * b->vy;
	cp.vy = a->vz * b->vx - a->vx * b->vz;
	cp.vz = a->vx * b->vy - a->vy * b->vx;

	// NOTE: cp.vw is left unset, as in the original
	*out = cp;

	return out;
}

// [0x527f27] [D]
void Normalise(VECTOR4 *v)
{
	float len;
	float scale;

	len = (float)sqrt(v->vx * v->vx + v->vy * v->vy + v->vz * v->vz);
	scale = 1.0f / len;

	v->vx *= scale;
	v->vy *= scale;
	v->vz *= scale;
}

