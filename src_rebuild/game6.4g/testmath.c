// [0x529142] [D]
void NormQuaternion(QUATERNION *quat)
{
	float len;

	len = (float)sqrt(quat->v.vx * quat->v.vx + quat->v.vy * quat->v.vy + quat->v.vz * quat->v.vz + quat->s * quat->s);

	if (len == 0.0f)
	{
		IdentityQuaternion(quat);
	}
	else
	{
		len = 1.0f / len;

		quat->v.vx *= len;
		quat->v.vy *= len;
		quat->v.vz *= len;
		quat->s *= len;
	}
}

// [0x5291f3] [D]
void Matrix2Quaternion(MATRIX *mat, QUATERNION *out)
{
	float s4;

	out->s = (float)sqrt((mat->m[0][0] + mat->m[1][1] + mat->m[2][2] + 1.0f) / 4.0f);

	s4 = out->s * 4.0f;

	out->v.vx = (mat->m[2][1] - mat->m[1][2]) / s4;
	out->v.vy = (mat->m[0][2] - mat->m[2][0]) / s4;
	out->v.vz = (mat->m[1][0] - mat->m[0][1]) / s4;
}

// [0x529279] [D]
void Quaternion2Matrix(QUATERNION *qua, MATRIX *out)
{
	float xx;
	float sz;
	float sy;
	float sx;
	float zz;
	float zx;
	float yz;
	float yy;
	float xy;

	xx = qua->v.vx * qua->v.vx * 2.0f;
	yy = qua->v.vy * qua->v.vy * 2.0f;
	zz = qua->v.vz * qua->v.vz * 2.0f;
	xy = qua->v.vx * qua->v.vy * 2.0f;
	yz = qua->v.vy * qua->v.vz * 2.0f;
	zx = qua->v.vz * qua->v.vx * 2.0f;
	sx = qua->s * qua->v.vx * 2.0f;
	sy = qua->s * qua->v.vy * 2.0f;
	sz = qua->s * qua->v.vz * 2.0f;

	out->m[0][0] = 1.0f - yy - zz;
	out->m[0][1] = xy - sz;
	out->m[0][2] = zx + sy;
	out->m[1][0] = xy + sz;
	out->m[1][1] = 1.0f - zz - xx;
	out->m[1][2] = yz - sx;
	out->m[2][0] = zx - sy;
	out->m[2][1] = yz + sx;
	out->m[2][2] = 1.0f - xx - yy;
}

