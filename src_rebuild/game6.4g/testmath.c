// [0x52865b] [D]
// Whether (tx, ty) is inside a convex polygon (xy of verts) of either winding.
// NOTE: the winding is computed from the first three vertices on every pass
int PointInPoly(int nverts, VECTOR4 *verts, float tx, float ty)
{
	float y;
	float x;
	float ny;
	float orientation;
	int i;
	float nx;

	for (i = 0; i < nverts; i++)
	{
		nx = verts[(i + 1) % nverts].vy - verts[i].vy;
		ny = verts[i].vx - verts[(i + 1) % nverts].vx;

		x = tx - verts[i].vx;
		y = ty - verts[i].vy;

		orientation = (verts[0].vx - verts[1].vx) * (verts[0].vy - verts[2].vy) - (verts[0].vy - verts[1].vy) * (verts[0].vx - verts[2].vx);

		if (orientation < 0.0f)
		{
			if (x * nx + y * ny < 0.0f)
				return 0;
		}
		else if (x * nx + y * ny > 0.0f)
		{
			return 0;
		}
	}

	return 1;
}

// [0x528790] [D]
int PointInQuad2d(int tx, int ty, XYPAIR *verts)
{
	if ((verts[1].y - verts[0].y) * (tx - verts[0].x) - (verts[1].x - verts[0].x) * (ty - verts[0].y) < 0)
		return 0;

	if ((verts[2].y - verts[1].y) * (tx - verts[1].x) - (verts[2].x - verts[1].x) * (ty - verts[1].y) < 0)
		return 0;

	if ((verts[3].y - verts[2].y) * (tx - verts[2].x) - (verts[3].x - verts[2].x) * (ty - verts[2].y) < 0)
		return 0;

	return (verts[0].y - verts[3].y) * (tx - verts[3].x) - (verts[0].x - verts[3].x) * (ty - verts[3].y) >= 0;
}

// [0x528884] [D]
int PointInTri2d(int tx, int ty, XYPAIR *verts)
{
	if ((verts[1].y - verts[0].y) * (tx - verts[0].x) - (verts[1].x - verts[0].x) * (ty - verts[0].y) < 0)
		return 0;

	if ((verts[2].y - verts[1].y) * (tx - verts[1].x) - (verts[2].x - verts[1].x) * (ty - verts[1].y) < 0)
		return 0;

	return (verts[0].y - verts[2].y) * (tx - verts[2].x) - (verts[0].x - verts[2].x) * (ty - verts[2].y) >= 0;
}

// [0x52893b] [D]
// NOTE: no name in the database; the intersection (ix, iz) of segments AB and CD in integers
// (rounded); 0: none, 2: parallel
int sub_52893B(XYPAIR *vA, XYPAIR *vB, XYPAIR *vC, XYPAIR *vD, int *ix, int *iz)
{
	int rz;
	int rx;
	int half;
	int dABx;
	int dDCy;
	int num;
	int dBAy;
	int cCD;
	int cAB;
	int dD;
	int dC;
	int denom;
	int dB;
	int dCDx;
	int dA;

	// C and D on the same side of AB: no intersection
	dBAy = vB->y - vA->y;
	dABx = vA->x - vB->x;
	cAB = vA->y * vB->x - vB->y * vA->x;
	dC = vC->x * dBAy + cAB + vC->y * dABx;
	dD = vD->x * dBAy + cAB + vD->y * dABx;

	if (dC && dD && (dD ^ dC) >= 0)
		return 0;

	// A and B on the same side of CD
	dDCy = vD->y - vC->y;
	dCDx = vC->x - vD->x;
	cCD = vC->y * vD->x - vD->y * vC->x;
	dA = vA->x * dDCy + cCD + vA->y * dCDx;
	dB = vB->x * dDCy + cCD + vB->y * dCDx;

	if (dA && dB && (dB ^ dA) >= 0)
		return 0;

	denom = dCDx * dBAy - dABx * dDCy;

	if (dCDx * dBAy == dABx * dDCy)
		return 2;

	// half the denominator, for rounding
	if (denom >= 0)
		half = denom / 2;
	else
		half = (dABx * dDCy - dCDx * dBAy) / 2;

	num = cCD * dABx - cAB * dCDx;

	if (num >= 0)
		rx = num + half;
	else
		rx = num - half;

	*ix = rx / denom;

	num = cAB * dDCy - cCD * dBAy;

	if (num >= 0)
		rz = num + half;
	else
		rz = num - half;

	*iz = rz / denom;

	return 1;
}

// [0x528b25] [D]
// Clips segment AB against the box (pos: xmin, ymin, xmax, ymax in vx, vy, vz, vw); the clipped
// ends go to vMin / vMax. Returns whether the segment crosses the box edge.
int LineBoxIntersect(IVECTOR *pos, XYPAIR *vA, XYPAIR *vB, XYPAIR *vMin, XYPAIR *vMax)
{
	float dMin;
	float dMax;
	int dBAy;
	int dBAx;
	int result;

	dBAx = vB->x - vA->x;
	dBAy = vB->y - vA->y;

	result = 0;

	if (!dBAx && !dBAy)
		return 0;

	dMin = 0.0f;
	dMax = 1.0f;

	if (LineIntersect(dBAx, pos->vx - vA->x, &dMin, &dMax) &&
		LineIntersect(-dBAx, vA->x - pos->vz, &dMin, &dMax) &&
		LineIntersect(dBAy, pos->vy - vA->y, &dMin, &dMax) &&
		LineIntersect(-dBAy, vA->y - pos->vw, &dMin, &dMax))
	{
		if (dMax < 1.0f)
		{
			vMax->x = float_to_int(dMax * (float)dBAx) + vA->x;
			vMax->y = float_to_int(dMax * (float)dBAy) + vA->y;
			result = 1;
		}

		if (dMin > 0.0f)
		{
			vMin->x = float_to_int(dMin * (float)dBAx) + vA->x;
			vMin->y = float_to_int(dMin * (float)dBAy) + vA->y;
			return 1;
		}
	}

	return result;
}

// [0x528d27] [D]
// One slab of LineBoxIntersect (Liang-Barsky): narrows [dMin, dMax]; 0 when outside.
int LineIntersect(int dA, int dB, float *dMin, float *dMax)
{
	float d;

	if (dA > 0)
	{
		d = (float)dB / (float)dA;

		if (d > *dMax)
			return 0;

		if (d > *dMin)
			*dMin = d;
	}
	else if (dA < 0)
	{
		d = (float)dB / (float)dA;

		if (d < *dMin)
			return 0;

		if (d < *dMax)
			*dMax = d;
	}
	else if (dB > 0)
	{
		return 0;
	}

	return 1;
}

