// [0x4c0a60] [D]
void LogQuick(char *text)
{
	FILE *handle;

	if (!gDebugLog)
		return;

	handle = fopen("debug.log", "r+t");

	if (handle && log_size == 0)
	{
		fclose(handle);
		handle = fopen("debug.log", "wt");
	}
	else
	{
		if (handle)
			fclose(handle);

		handle = fopen("debug.log", "a+t");
	}

	if (handle)
	{
		fprintf(handle, "%s\n", text);
		log_size = ftell(handle);
		fclose(handle);
	}
}

// [0x4c0b1d] [D]
void LogTimestamp(char *text)
{
	char buffer[256];
	SYSTEMTIME time;

	GetSystemTime(&time);
	sprintf(buffer, "%s (%d:%02d.%02d)", text, time.wHour, time.wMinute, time.wSecond);
	LogQuick(buffer);
}

