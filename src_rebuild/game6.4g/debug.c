// [0x4c0c61] [D]
void DBGShowMessages(void)
{
	int i;

	TextOffset(0, 0);

	for (i = 0; i < MAX_DBG_MESSAGES; i++)
	{
		if (DBGMessages[i].string == NULL)
			continue;

		AddTextToList(DBGMessages[i].string);
		AddTextToList(": ");

		switch (DBGMessages[i].type)
		{
			case 0:		// hex
				if (DBGMessages[i].size == 0)
					sprintf(DBGTemp, "%#04x", *(u_char *)DBGMessages[i].varloc);
				else if (DBGMessages[i].size == 1)
					sprintf(DBGTemp, "%#06x", *(short *)DBGMessages[i].varloc);
				else
					sprintf(DBGTemp, "%#010x", *(int *)DBGMessages[i].varloc);

				AddTextToList(DBGTemp);
				break;
			case 1:		// BUG: %b is not a printf format
				if (DBGMessages[i].size == 0)
					sprintf(DBGTemp, "0%bb", *(u_char *)DBGMessages[i].varloc);
				else if (DBGMessages[i].size == 1)
					sprintf(DBGTemp, "0%bb", *(short *)DBGMessages[i].varloc);
				else
					sprintf(DBGTemp, "0%bb", *(int *)DBGMessages[i].varloc);

				AddTextToList(DBGTemp);
				break;
			case 2:		// unsigned
				if (DBGMessages[i].size == 0)
					sprintf(DBGTemp, "%u", *(u_char *)DBGMessages[i].varloc);
				else if (DBGMessages[i].size == 1)
					sprintf(DBGTemp, "%u", *(unsigned short *)DBGMessages[i].varloc);
				else
					sprintf(DBGTemp, "%u", *(int *)DBGMessages[i].varloc);

				AddTextToList(DBGTemp);
				break;
			case 3:		// signed
				if (DBGMessages[i].size == 0)
					sprintf(DBGTemp, "%d", *(signed char *)DBGMessages[i].varloc);
				else if (DBGMessages[i].size == 1)
					sprintf(DBGTemp, "%d", *(short *)DBGMessages[i].varloc);
				else
					sprintf(DBGTemp, "%d", *(int *)DBGMessages[i].varloc);

				AddTextToList(DBGTemp);
				break;
			case 4:
				sprintf(DBGTemp, "%f", *(float *)DBGMessages[i].varloc);
				AddTextToList(DBGTemp);
				break;
			case 5:
				sprintf(DBGTemp, "%s", (char *)DBGMessages[i].varloc);
				AddTextToList(DBGTemp);
				break;
		}

		TextReset();
	}
}

// [0x4c0ff2] [D]
void DBGAddWatch(char *message, void *variable, char type, char size)
{
	int i;

	for (i = 0; i < MAX_DBG_MESSAGES; i++)
	{
		if (DBGMessages[i].string == NULL)
		{
			DBGMessages[i].string = message;
			DBGMessages[i].varloc = variable;
			DBGMessages[i].type = type;
			DBGMessages[i].size = size;
			return;
		}
	}
}

// [0x4c1061] [D]
void DBGRemoveWatch(void *variable)
{
	int i;

	for (i = 0; i < MAX_DBG_MESSAGES; i++)
	{
		if (DBGMessages[i].varloc == variable)
		{
			DBGMessages[i].string = NULL;
			DBGMessages[i].varloc = NULL;
			DBGMessages[i].type = 0;
			DBGMessages[i].size = 0;
			return;
		}
	}
}

// [0x4c10d0] [D]
// Writes the frame rate to the top of an 8 bit, 640 wide screen.
void DisplayDebugStats(char *screen, char fg, char bg)
{
	static int last_time;	// 0xb9f518
	static int fps;			// 0xb9f51c
	static int frames;		// 0xb9f520

	DWORD elapsed;
	char text[32];
	char *str;
	char *dest;
	char chr;
	char row;
	int x;
	int y;

	frames++;
	elapsed = timeGetTime() - last_time;

	if (elapsed > 1000)
	{
		fps = 1000 * frames / elapsed;
		last_time = timeGetTime();
		frames = 0;
	}

	sprintf(text, "%dfps    ", fps);

	str = text;

	while ((chr = *str++) != 0)
	{
		if (chr >= 'a' && chr <= 'z')
			chr -= 0x60;

		dest = screen;

		for (y = 0; y < 8; y++)
		{
			row = DebugFont[8 * chr + y];

			for (x = 0; x < 8; x++)
			{
				if (row & 0x80)
					*dest = fg;
				else
					*dest = bg;

				dest++;
				row *= 2;
			}

			dest += 632;
		}

		screen += 8;
	}
}
