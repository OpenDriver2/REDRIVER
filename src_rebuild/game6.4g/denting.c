// Gives a car (-1 the player) a fresh copy of its clean model unless the slot already has the
// model (the player car is always copied).
void CreateDentableCar(int id)
{
	int slot;
	int type;

	slot = id + 1;

	if (id == -1)
		type = 0;
	else
		type = (unsigned char)civilian_ai_data[id].model;

	if ((unsigned char)gOldCarType[slot] != type || type == 0)
	{
		gOldCarType[slot] = type;

		CopyMem(gTempCarVertDump[slot], (void *)gCarCleanModelPtr[type]->vertices, sizeof(VECTOR4) * (unsigned short)gCarCleanModelPtr[type]->num_vertices);
		CopyMem(gTempCarNormalDump[slot], (void *)gCarCleanModelPtr[type]->normals, sizeof(VECTOR4) * (unsigned short)gCarCleanModelPtr[type]->num_polys);

		if (id != -1)
			CopyMem(gTempCarPolyDump[slot], (void *)gCarCleanModelPtr[type]->poly_block, gTempCarPolyDumpSize[type]);

		gCarMaxDamage[slot] = 50;
	}
}

// [0x4c1aea] [D]
// Dents a car (-1 the player) by the damage of its six zones: moves the zone vertices of a fresh
// copy of the clean model (a vertex in two zones gets the average), recalculates the polygon
// normals, updates the damage textures and the car's gCarMaxDamage (50 undamaged, down to 0).
void ApplyDentingOnCar(int id)
{
	VECTOR4 *car_verts;
	VECTOR4 *car_normals;
	VECTOR4 *car_damage;
	VECTOR4 *v0;
	VECTOR4 *v1;
	VECTOR4 *v2;
	VECTOR4 a;
	VECTOR4 b;
	VECTOR4 n;
	float *zone_damage;
	float scale;
	float len;
	int *poly_block;
	unsigned char vert;
	int max_damage;
	int damage;
	int slot;
	int type;
	int i;
	int j;
	int p;

	max_damage = 0;

	slot = id + 1;

	if (id == -1)
		type = 0;
	else
		type = (unsigned char)civilian_ai_data[id].model;

	gOldCarType[slot] = -1;

	CopyMem(gTempCarVertDump[slot], (void *)gCarCleanModelPtr[type]->vertices, sizeof(VECTOR4) * (unsigned short)gCarCleanModelPtr[type]->num_vertices);

	memset(gZoneVertDamageDump, 0, sizeof(gZoneVertDamageDump));

	// process damage regions
	for (i = 0; i < 6; i++)
	{
		damage = car_data[slot].damage[i];

		if (max_damage < damage)
			max_damage = car_data[slot].damage[i];

		// 80 damage verts each (hardcoded)
		for (j = 0; j < 80; j++)
		{
			vert = gDamageZoneVerts[type][i][j];

			if (vert == 255)
				break;

			if (gZoneVertDamageDump[vert] == 0.0f)
				gZoneVertDamageDump[vert] = (float)damage + gZoneVertDamageDump[vert];
			else
				gZoneVertDamageDump[vert] = (float)((damage + float_to_int(gZoneVertDamageDump[vert])) >> 1);

			if (gZoneVertDamageDump[vert] > 4096.0f)
				gZoneVertDamageDump[vert] = 4096.0f;
		}
	}

	car_verts = gTempCarVertDump[slot];
	car_damage = gCarUnitDamage[type];
	zone_damage = gZoneVertDamageDump;

	// NOTE: the counter is a byte as in the original: a model with more than 255 vertices would
	// never finish (the car models have fewer)
	for (vert = 0; vert < (unsigned short)gCarCleanModelPtr[type]->num_vertices; vert++)
	{
		scale = (float)float_to_int(*zone_damage);

		car_verts->vx = scale * car_damage->vx + car_verts->vx;
		car_verts->vy = scale * car_damage->vy + car_verts->vy;
		car_verts->vz = scale * car_damage->vz + car_verts->vz;

		car_verts++;
		car_damage++;
		zone_damage++;
	}

	poly_block = (int *)gCarCleanModelPtr[type]->poly_block;
	car_normals = gTempCarNormalDump[slot];
	car_verts = gTempCarVertDump[slot];

	// the normal of each polygon from its first three vertices (words 2 - 4 of the polygon),
	// vw the plane distance
	for (p = 0; p < (unsigned short)gCarCleanModelPtr[type]->num_polys; p++)
	{
		v0 = &car_verts[poly_block[2]];
		v1 = &car_verts[poly_block[3]];
		v2 = &car_verts[poly_block[4]];

		a.vx = v0->vx - v1->vx;
		a.vy = v0->vy - v1->vy;
		a.vz = v0->vz - v1->vz;

		b.vx = v2->vx - v1->vx;
		b.vy = v2->vy - v1->vy;
		b.vz = v2->vz - v1->vz;

		n.vx = -(a.vy * b.vz - a.vz * b.vy);
		n.vy = -(a.vz * b.vx - a.vx * b.vz);
		n.vz = -(a.vx * b.vy - a.vy * b.vx);

		len = (float)sqrt(n.vx * n.vx + n.vy * n.vy + n.vz * n.vz);

		if (len == 0.0f)
			len = 1.0f;

		scale = 1.0f / len;

		car_normals->vx = n.vx * scale;
		car_normals->vy = n.vy * scale;
		car_normals->vz = n.vz * scale;
		car_normals->vw = v1->vx * car_normals->vx + v1->vy * car_normals->vy + v1->vz * car_normals->vz;

		poly_block = (int *)((char *)poly_block + PolySizes[*(unsigned char *)poly_block]);

		car_normals++;
	}

	BlitTextDent(slot);

	max_damage = 50 - (max_damage >> 6);

	if (max_damage < 0)
		max_damage = 0;

	gCarMaxDamage[slot] = max_damage;
}

