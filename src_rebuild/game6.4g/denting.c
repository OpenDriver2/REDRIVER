// [0x4c332c] [D]
// Undents the textures of a car slot: the player car's damage page from its texture set, an AI
// car's polygons from its clean model.
void InitTextDents(int slot)
{
	int model;
	int tset;
	int i;

	if (slot)
	{
		model = (unsigned char)civilian_ai_data[slot - 1].model;
		CopyMem(gTempCarPolyDump[slot], (void *)gCarCleanModelPtr[model]->poly_block, gTempCarPolyDumpSize[model]);
	}
	else
	{
		tset = gDamageTPages[0][0]->tset;

		CopyTexture(TextureSlots[tset].data, gPlayerCarDamageTexture);
		ReplaceTextureSet(tset, gPlayerCarDamageTexture);

		for (i = 7; i >= 0; i--)
			player_dent_stage[i] = 0;
	}
}

// [0x4c33e3] [D]
// Shows a car slot's damage. The player car: blits the dent stage of each zone (6 stages over
// the damage) into its damage texture pages. An AI car: takes the damaged model's polygons in
// the dented regions (front, back: damage over 1323 in either zone, sides over 1000).
void BlitTextDent(int slot)
{
	TEX_INFO *stage_tex;
	TEX_INFO *page_tex;
	unsigned char *car_polys;
	unsigned char *temp_polys;
	char *region;
	unsigned int polys_size;
	int dented[8];
	int num_polys;
	int changed;
	int stage;
	int page;
	int model;
	int zone;
	int i;
	int j;

	if (gDisableDenting)
		return;

	if (slot)
	{
		model = (unsigned char)civilian_ai_data[slot - 1].model;

		// NOTE: the original reads these as the locals after num_polys on the stack: region 7
		// reads `model` (dented unless model 0)
		if (car_data[slot].damage[0] <= 1323 && car_data[slot].damage[1] <= 1323)
		{
			dented[1] = 0;
			dented[2] = 0;
		}
		else
		{
			dented[1] = 1;
			dented[2] = 1;
		}

		dented[3] = car_data[slot].damage[2] > 1000;

		if (car_data[slot].damage[3] <= 1323 && car_data[slot].damage[4] <= 1323)
		{
			dented[4] = 0;
			dented[5] = 0;
		}
		else
		{
			dented[4] = 1;
			dented[5] = 1;
		}

		dented[6] = car_data[slot].damage[5] > 1000;
		dented[7] = model;

		car_polys = (unsigned char *)gCarDamModelPtr[model]->poly_block;
		temp_polys = (unsigned char *)gTempCarPolyDump[slot];
		region = gCarPolyDentRegionLookup[model];
		num_polys = (unsigned short)gCarCleanModelPtr[model]->num_polys;

		if ((unsigned short)gCarDamModelPtr[model]->num_polys == num_polys)
		{
			for (i = 0; i < num_polys; i++)
			{
				polys_size = PolySizes[*car_polys];
				zone = (unsigned char)*region++;

				if (zone && dented[zone])
					CopyMem(temp_polys, car_polys, polys_size);

				// the models' polygons must match one for one
				if (*car_polys != *temp_polys || polys_size != (unsigned int)PolySizes[*temp_polys])
					break;

				car_polys += polys_size;
				temp_polys += PolySizes[*temp_polys];
			}
		}
	}
	else
	{
		changed = 0;

		for (i = 5; i >= 0; i--)
		{
			stage = (6 * car_data[0].damage[i]) >> 12;

			if (stage > 5)
				stage = 5;

			if ((unsigned char)player_dent_stage[i] != stage)
			{
				for (j = 0; j < 3; j++)
				{
					page = gHDCarDamageTPages[gPlayerCarModelType][i][j];

					if (page == -1)
						break;

					stage_tex = gDamageTPages[page][stage];
					page_tex = gDamageTPages[page][0];

					if (stage_tex && page_tex)
						BlitTexture(TextureSlots[stage_tex->tset].data, stage_tex->u, stage_tex->v, stage_tex->w, stage_tex->h, gPlayerCarDamageTexture, page_tex->u, page_tex->v);
				}

				player_dent_stage[i] = stage;
				changed = 1;
			}
		}

		if (changed)
			ReplaceTextureSet(gDamageTPages[0][0]->tset, gPlayerCarDamageTexture);
	}
}

// [0x4c375b] [D]
// Queues a car (-1 the player) for ApplyDentingOnCar, once.
void QueueDentCar(int id)
{
	int found;
	int i;

	found = 0;

	if (NumCarsToDent)
	{
		for (i = 0; i < NumCarsToDent; i++)
		{
			if (DentQueue[i] == id)
			{
				found = 1;
				break;
			}
		}
	}

	if (!found)
		DentQueue[NumCarsToDent++] = id;
}

// [0x4c37cf] [D]
void ProcessDentQueue(void)
{
	while (NumCarsToDent)
		ApplyDentingOnCar(DentQueue[--NumCarsToDent]);
}
