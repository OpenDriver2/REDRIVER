// [0x4c21a6] [D]
// Throws hubcap `wheel` off the player car (when going forward and the hubcap is still on): it
// starts at the wheel with the car's velocity plus the spin of the car.
void LoseHubcap(int wheel, int velocity)
{
	SVECTOR ang;
	VECTOR4 dir;
	CAR_DATA *cp;
	int spin;

	cp = car_data;

	ang.vx = 0;
	ang.vy = 0;
	ang.vz = 10;
	ang.pad = 0;

	if ((double)car_data[0].wheel_speed >= 0.0 && gHubcap.Present[wheel])
	{
		gHubcap.Present[wheel] = 0;

		gHubcap.Position.vx = gHubcap.Offset[wheel].vx;
		gHubcap.Position.vy = gHubcap.Offset[wheel].vy;
		gHubcap.Position.vz = gHubcap.Offset[wheel].vz;

		CurrentRotationMatrix = float_body_mat;
		MatrixRotateB(&gHubcap.Position);

		gHubcap.Position.vx = gHubcap.Position.vx + (float)cp->location.vx;
		gHubcap.Position.vy = gHubcap.Position.vy - (float)cp->location.vy;
		gHubcap.Position.vz = gHubcap.Position.vz + (float)cp->location.vz;

		gHubcap.Orientation = float_body_mat[0];
		CalcMatrixXYZ(&gHubcap.LocalOrientation, &ang);

		// the left side hubcaps face the other way
		if (wheel == 3 || wheel == 2)
		{
			gHubcap.Orientation.m[0][0] = -gHubcap.Orientation.m[0][0];
			gHubcap.Orientation.m[1][0] = -gHubcap.Orientation.m[1][0];
			gHubcap.Orientation.m[2][0] = -gHubcap.Orientation.m[2][0];
			gHubcap.Orientation.m[0][2] = -gHubcap.Orientation.m[0][2];
			gHubcap.Orientation.m[1][2] = -gHubcap.Orientation.m[1][2];
			gHubcap.Orientation.m[2][2] = -gHubcap.Orientation.m[2][2];
		}

		spin = cp->st.n.angularVelocity[1] >> 12;

		dir.vx = (float)spin * gHubcap.Offset[wheel].vz / 4096.0f + (float)(cp->st.n.linearVelocity[0] >> 12);
		dir.vy = (float)(cp->st.n.linearVelocity[1] >> 12) + 0.0f;
		dir.vz = (float)-spin * gHubcap.Offset[wheel].vx / 4096.0f + (float)(cp->st.n.linearVelocity[2] >> 12);
		dir.vw = 0.0f;		// NOTE: not set in the original (stack garbage)

		gHubcap.Direction = dir;
		gHubcap.Duration = 100;
	}
}

// [0x4c242f] [D]
// drawing: draws the flying hubcap and its shadow. Otherwise moves it (it bounces off the
// ground) and, when none is flying, loses the next hubcap once its time is up and the car spins
// hard enough.
void MoveHubcap(int drawing)
{
	VECTOR4 pos;
	VECTOR4 s0;
	VECTOR4 s1;
	VECTOR4 s2;
	VECTOR4 s3;
	GrVertex q3;
	GrVertex q2;
	GrVertex q1;
	GrVertex q0;
	MATRIX mat;
	float scale;
	int clip;
	int spin;

	if (drawing)
	{
		if (gHubcap.Duration < 1)
			return;

		MulMatrix(&gHubcap.Orientation, &gHubcap.LocalOrientation, &mat);

		clip = FrustrumCheck(&gHubcap.Position, gHubcapModelPtr->bounding_sphere);

		if (!clip || !cop_texture)
			return;

		pos.vx = gHubcap.Position.vx - camera_position.vx;
		pos.vy = gHubcap.Position.vy - camera_position.vy;
		pos.vz = gHubcap.Position.vz - camera_position.vz;

		CurrentRotationMatrix = &inv_camera_matrix;
		MatrixRotate(&pos);

		if (gPreviousAlpha != 1)
		{
			grAlphaCombine(GR_COMBINE_FUNCTION_SCALE_OTHER, GR_COMBINE_FACTOR_ONE, GR_COMBINE_LOCAL_ITERATED, GR_COMBINE_OTHER_TEXTURE, FXTRUE);
			grAlphaTestFunction(GR_CMP_GREATER);
			gPreviousAlpha = 1;
		}

		if (clip == 1)
			DrawObject(gHubcapModelPtr, &mat, &pos, 0);
		else
			DrawObject(gHubcapModelPtr, &mat, &pos, 1);

		if (gPreviousAlpha != 0)
		{
			grAlphaCombine(GR_COMBINE_FUNCTION_SCALE_OTHER, GR_COMBINE_FACTOR_ONE, GR_COMBINE_LOCAL_ITERATED, GR_COMBINE_OTHER_CONSTANT, FXTRUE);
			grAlphaTestFunction(GR_CMP_ALWAYS);
			gPreviousAlpha = 0;
		}

		if (!gDrawShadows)
			return;

		// a 50 x 50 shadow quad (the cop_texture) on the ground under the hubcap
		s0.vx = gHubcap.Position.vx - camera_position.vx - 25.0f;
		s0.vz = gHubcap.Position.vz - camera_position.vz - 25.0f;
		s1.vx = gHubcap.Position.vx - camera_position.vx + 25.0f;
		s1.vz = s0.vz;
		s2.vx = s1.vx;
		s2.vz = gHubcap.Position.vz - camera_position.vz + 25.0f;
		s3.vx = s0.vx;
		s3.vz = s2.vz;

		s0.vy = (float)(hubcap_floor - 5) - camera_position.vy;
		s1.vy = s0.vy;
		s2.vy = s0.vy;
		s3.vy = s0.vy;

		CurrentRotationMatrix = &inv_camera_matrix;
		MatrixRotate(&s0);
		MatrixRotate(&s1);
		MatrixRotate(&s2);
		MatrixRotate(&s3);

		if (s0.vz <= 50.0f || s1.vz <= 50.0f || s2.vz <= 50.0f || s3.vz <= 50.0f)
			return;

		if (s0.vz >= far_clip || s1.vz >= far_clip || s2.vz >= far_clip || s3.vz >= far_clip)
			return;

		q0.oow = ooz_table[float_to_int(s0.vz)];
		scale = DIST * q0.oow;
		q0.x = s0.vx * scale + screen_xmid - VERTEX_SNAPPER;
		q0.y = s0.vy * scale + screen_ymid - VERTEX_SNAPPER;

		q1.oow = ooz_table[float_to_int(s1.vz)];
		scale = DIST * q1.oow;
		q1.x = s1.vx * scale + screen_xmid - VERTEX_SNAPPER;
		q1.y = s1.vy * scale + screen_ymid - VERTEX_SNAPPER;

		q2.oow = ooz_table[float_to_int(s2.vz)];
		scale = DIST * q2.oow;
		q2.x = s2.vx * scale + screen_xmid - VERTEX_SNAPPER;
		q2.y = s2.vy * scale + screen_ymid - VERTEX_SNAPPER;

		q3.oow = ooz_table[float_to_int(s3.vz)];
		scale = DIST * q3.oow;
		q3.x = s3.vx * scale + screen_xmid - VERTEX_SNAPPER;
		q3.y = s3.vy * scale + screen_ymid - VERTEX_SNAPPER;

		q3.r = 100.0f;
		q2.r = 100.0f;
		q1.r = 100.0f;
		q0.r = 100.0f;
		q3.g = 100.0f;
		q2.g = 100.0f;
		q1.g = 100.0f;
		q0.g = 100.0f;
		q3.b = 100.0f;
		q2.b = 100.0f;
		q1.b = 100.0f;
		q0.b = 100.0f;

		SwapPalette(0);

		if (cop_texture->tset != last_tset)
		{
			last_tset = cop_texture->tset;
			grTexSource(GR_TMU0, TextureSlots[cop_texture->tset].texture_ram_address, GR_MIPMAPLEVELMASK_BOTH, TextureSlots[cop_texture->tset].TInfo);
		}

		q0.tmuvtx[0].sow = (float)cop_texture->u * q0.oow;
		q0.tmuvtx[0].tow = (float)cop_texture->v * q0.oow;
		q1.tmuvtx[0].sow = (float)cop_texture->w * q1.oow;
		q1.tmuvtx[0].tow = (float)cop_texture->v * q1.oow;
		q2.tmuvtx[0].sow = (float)cop_texture->w * q2.oow;
		q2.tmuvtx[0].tow = (float)cop_texture->h * q2.oow;
		q3.tmuvtx[0].sow = (float)cop_texture->u * q3.oow;
		q3.tmuvtx[0].tow = (float)cop_texture->h * q3.oow;

		if (last_trans_on != 2)
		{
			grAlphaBlendFunction(GR_BLEND_ZERO, GR_BLEND_ONE_MINUS_SRC_COLOR, GR_BLEND_ONE, GR_BLEND_ZERO);
			last_trans_on = 2;
		}

		guDrawTriangleWithClip(&q0, &q1, &q2);
		guDrawTriangleWithClip(&q0, &q2, &q3);

		return;
	}

	if (!GamePaused && gHubcapTime > 0)
		gHubcapTime--;

	if (gHubcap.Duration >= 1 || gHubcapTime)
	{
		if (!GamePaused)
			gHubcap.Duration--;

		if (gHubcap.Duration >= 1 && !GamePaused)
		{
			gHubcap.Position.vx = gHubcap.Direction.vx / 2.0f + gHubcap.Position.vx;
			gHubcap.Position.vy = gHubcap.Direction.vy / 2.0f + gHubcap.Position.vy;
			gHubcap.Position.vz = gHubcap.Direction.vz / 2.0f + gHubcap.Position.vz;

			RotMatrixX(&gHubcap.LocalOrientation, 110);

			gHubcap.Direction.vy = gHubcap.Direction.vy + 5.0f;

			hubcap_floor = -MapHeight(&gHubcap.Position) - 60;

			if (gHubcap.Position.vy >= (float)hubcap_floor)
			{
				gHubcap.Direction.vy = -(gHubcap.Direction.vy * 0.7f);
				gHubcap.Position.vy = (float)hubcap_floor;
			}
		}
	}
	else
	{
		spin = car_data[0].st.n.angularVelocity[2] + car_data[0].st.n.angularVelocity[1] + car_data[0].st.n.angularVelocity[0];

		if (spin < -1000000)
		{
			LoseHubcap(2, spin);
			gHubcapTime = CalcHubcapTime[CalcHubcapNum++];
		}
		else if (spin > 1000000)
		{
			LoseHubcap(0, spin);
			gHubcapTime = CalcHubcapTime[CalcHubcapNum++];
		}
	}
}

// [0x4c2e81] [D]
// Copies a 256 x 256 16 bit texture page.
void CopyTexture(const void *src, void *dst)
{
	memcpy(dst, src, 0x20000);
}

// [0x4c2e99] [D]
// Copies a w x h rectangle between 256 x 256 16 bit texture pages.
void BlitTexture(void *src, int u, int v, unsigned int w, int h, void *dst, int du, int dv)
{
	char *s;
	char *d;

	s = (char *)src + 512 * v + 2 * u;
	d = (char *)dst + 512 * dv + 2 * du;

	do
	{
		memcpy(d, s, 2 * w);

		s += 512;
		d += 512;
	} while (--h);
}

// [0x4c2f09] [D]
// Copies a w x h rectangle between 256 x 256 8 bit texture pages.
void BlitTexture32(void *src, int u, int v, unsigned int w, int h, void *dst, int du, int dv)
{
	char *s;
	char *d;

	s = (char *)src + 256 * v + u;
	d = (char *)dst + 256 * dv + du;

	do
	{
		memcpy(d, s, w);

		s += 256;
		d += 256;
	} while (--h);
}

