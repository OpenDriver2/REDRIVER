"""Keep the source headers in sync: every global and function another file uses is declared in its
owner's header, and the .c files include headers instead of writing `extern`.

Usage:
  python tools/headers.py            # update headers and sources
  python tools/headers.py --dry      # only report what would change

Owner header: `<file>.h` next to the owner `.c` (`dr_<name>.h` when the name would hide a C runtime
header). Each owner header has a generated block between the GENERATED markers, rewritten on every
run; text outside the block is kept as it is (hand-written declarations and notes go there).
`dr_globals.h` holds the globals whose owner is not known (see `progress.py --globals`).

- Globals: owner and IDA type from tools/ida/globals.tsv (via progress.py); the declaration is taken
  from the definition in the owner .c, else from the header, else from a hand-written extern, else
  from IDA.
- Functions: every non-static function defined in a .c is declared in that file's header (from its
  definition); a function still declared `extern` by hand somewhere and not defined (a stub) goes to
  the header of its IDA folder (tools/ida/functions.tsv). A prototype using a type that only its .c
  defines is left out (reported) - move the type to dr_types.h.
- An `extern` under a comment containing "tools/headers.py: keep" stays in its .c (e.g. glide2x.c
  must not include Engine/3dfx/gfxinit.h).
- Sources: `extern` declarations of names now in a header are removed (with the `// NOTE:` lines
  right above them, which move to the header), the headers are #included after the existing
  includes, and section comments (`/* file.c */`) left without declarations are dropped.
Names declared in the hand-made headers (dr_types.h, D3DGlide/d3dglide.h, D3DGlide/glide_ptrs.h)
are left alone.
"""
import collections, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import progress as P

SRC = P.SRC
DRY = "--dry" in sys.argv
SECTIONS = ("globals", "functions", "functions not translated yet")
SECTION_TITLES = set("// " + s for s in SECTIONS)
BEGIN = "// --- GENERATED by tools/headers.py: edits between these markers are overwritten ---"
END = "// --- END GENERATED ---"
FIXED_HEADERS = {"dr_types.h", "D3DGlide/d3dglide.h", "D3DGlide/glide_ptrs.h"}
SHARED_OWNER = "dr_globals.c"
CRT_HEADERS = {"time.h", "math.h", "string.h", "stdio.h", "stdlib.h", "memory.h", "signal.h", "float.h",
               "limits.h", "ctype.h", "errno.h", "io.h", "process.h", "malloc.h", "search.h", "assert.h"}
NL = "\r\n"


def header_of(cfile):
    h = cfile[:-2] + ".h"
    d, b = os.path.split(h)
    if b.lower() in CRT_HEADERS:
        h = os.path.join(d, "dr_" + b).replace("\\", "/")
    return h


def read(rel):
    p = os.path.join(SRC, rel)
    return open(p, encoding="utf-8").read().replace("\r\n", "\n") if os.path.exists(p) else None


def write(rel, text):
    if DRY:
        return
    open(os.path.join(SRC, rel), "w", encoding="utf-8", newline=NL).write(text)


def sources(ext):
    for root, dirs, files in os.walk(SRC):
        for fn in files:
            if fn.endswith(ext):
                yield os.path.relpath(os.path.join(root, fn), SRC).replace("\\", "/")


def code_lines(text):
    """-> [(line, code)] where code has comments and string/char literals blanked."""
    out, in_block = [], False
    for line in text.split("\n"):
        code, i = [], 0
        while i < len(line):
            if in_block:
                j = line.find("*/", i)
                if j < 0:
                    i = len(line)
                else:
                    in_block, i = False, j + 2
                continue
            c = line[i]
            if line.startswith("//", i):
                break
            if line.startswith("/*", i):
                in_block, i = True, i + 2
                continue
            if c in "\"'":
                j = i + 1
                while j < len(line) and line[j] != c:
                    j += 2 if line[j] == "\\" else 1
                code.append(c + " " * max(0, j - i - 1) + c)
                i = j + 1
                continue
            code.append(c)
            i += 1
        out.append((line, "".join(code)))
    return out


def decl_name(body):
    """'int (FX_CALL **x[4])(int)' / 'void __declspec(noreturn) f(int)' / 'int a[2]' -> (name, is_func)."""
    b = re.sub(r"__declspec\s*\([^)]*\)", "", body)
    fp = re.match(r"[^(]*\(\s*[\w\s]*\*+\s*(\w+)\s*(?:\[[^\]]*\]\s*)*\)\s*\(", b)
    if fp:
        return fp.group(1), False
    fn = re.match(r"[^(]*?\b(\w+)\s*\(", b)
    if fn:
        return fn.group(1), True
    m = re.search(r"(\w+)\s*(?:\[[^\]]*\]\s*)*$", b)
    return (m.group(1) if m else None), False


def parse_c(rel):
    """-> (definitions {name: signature}, statics {name}, externs [(start, end, name, is_func, text)],
    local typedef names) of one .c file. Line numbers are 0-based, end exclusive."""
    lines = code_lines(read(rel))
    defs, statics, externs, typedefs = {}, set(), [], set()
    depth, i = 0, 0
    while i < len(lines):
        raw, code = lines[i]
        if depth == 0 and re.match(r"[A-Za-z_]", code):
            # gather a statement / signature up to ';' or '{' with balanced parentheses
            j, stmt = i, code
            while (stmt.count("(") > stmt.count(")") or not re.search(r"[;{)]\s*$|[;{]", stmt)) and j + 1 < len(lines):
                j += 1
                stmt += " " + lines[j][1].strip()
            nxt = j + 1
            while nxt < len(lines) and not lines[nxt][1].strip():
                nxt += 1
            s = " ".join(stmt.split())
            if s.startswith("typedef"):
                m = re.search(r"(\w+)\s*;\s*$", s) or re.search(r"\(\s*\w*\s*\*\s*(\w+)\s*\)", s)
                if m:
                    typedefs.add(m.group(1))
            elif s.startswith("extern") and s.endswith(";"):
                body = s[len("extern"):-1].strip()
                name, is_func = decl_name(body)
                if name:
                    externs.append((i, j + 1, name, is_func, body))
            elif s.endswith(")") and nxt < len(lines) and lines[nxt][1].strip().startswith("{") and "=" not in s:
                name, is_func = decl_name(s)
                if name and is_func:
                    if s.startswith("static"):
                        statics.add(name)
                    else:
                        defs[name] = s
            elif s.startswith("static"):
                m = re.search(r"\b(\w+)\s*\(", s)
                if m:
                    statics.add(m.group(1))
            # struct/enum bodies: `} NAME;`
        for m in re.finditer(r"\}\s*(\w+)\s*;", code):
            if depth == 1 and code.lstrip().startswith("}"):
                typedefs.add(m.group(1))
        depth += code.count("{") - code.count("}")
        i += 1
    return defs, statics, externs, typedefs


KEEP = "tools/headers.py: keep"


def kept(lines, start):
    """An extern under a comment block containing KEEP stays in its .c file."""
    k = start - 1
    while k >= 0 and (lines[k].startswith("extern") or lines[k].startswith("//")):
        if KEEP in lines[k]:
            return True
        if lines[k].startswith("//") and k > 0 and not lines[k - 1].startswith(("//", "extern")):
            break
        k -= 1
    return False


def fixed_names():
    """-> {name: hand-made header declaring it}."""
    names = {}
    for h in sorted(FIXED_HEADERS):
        t = read(h) or ""
        depth = 0
        for line, code in code_lines(t):
            c = code.strip()
            if depth == 0 and c.endswith(";") and re.match(r"[A-Za-z_]", c) and not c.startswith(("typedef", "#", "}")):
                name, is_func = decl_name(re.sub(r"^(extern|GLIDE_EXTERN)\s+", "", c[:-1]))
                if name:
                    names.setdefault(name, h)
            depth += code.count("{") - code.count("}")
    return names


def split_header(text):
    """-> (head, generated, tail) of an existing header; generated is None without markers."""
    if text is None:
        return None, None, None
    if BEGIN in text and END in text:
        a = text.index(BEGIN)
        b = text.index(END)
        return text[:a], text[a + len(BEGIN):b], text[b + len(END):]
    return text, None, ""


def header_decls(text):
    """-> {name: (decl text without extern, [comment lines])} from a header's declarations."""
    out, notes = {}, []
    for line in text.split("\n"):
        s = line.strip()
        if s in SECTION_TITLES:
            notes = []
            continue
        if s.startswith("//"):
            notes.append(s)
            continue
        m = re.match(r"extern\s+(.*);$", s)
        if m:
            name, is_func = decl_name(m.group(1))
            if name:
                out[name] = (m.group(1), notes)
        notes = []
    return out


def main():
    g, owner, guessed, gdefs, gexts = P.global_owners()
    for n in guessed:
        owner[n] = SHARED_OWNER
    translated = set(f for f, m in P.markers().values())
    fixed_in = fixed_names()
    fixed = set(fixed_in)

    func_folder = {}
    for line in open(P.FUNCS, encoding="utf-8"):
        folder, ea, name = line.rstrip("\n").split("\t")
        if name.startswith("_") and "." not in name and folder != "[THUNKS]":
            func_folder.setdefault(name[1:], P.folder_file(folder).replace(" (missing)", ""))

    parsed = {rel: parse_c(rel) for rel in sources(".c")}
    fdefs = {}                      # function -> (file, signature)
    for rel, (defs, statics, externs, typedefs) in parsed.items():
        for n, sig in defs.items():
            fdefs.setdefault(n, (rel, sig))

    # existing header declarations (to keep stable text and notes)
    existing = {}
    existing_in = {}            # generated declarations: name -> header
    hand = {}                   # declared by hand outside the block: name -> header
    for rel in sources(".h"):
        if rel in FIXED_HEADERS:
            continue
        head, gen, tail = split_header(read(rel))
        for n, d in header_decls(gen if gen is not None else head).items():
            existing[n] = d
            existing_in[n] = rel
        if gen is not None:
            for n in header_decls(head + tail):
                hand[n] = rel
    fixed |= set(hand)          # not regenerated, but their externs in .c files are replaced

    # what each header declares: name -> (owner .c, kind, decl, notes)
    entries = collections.defaultdict(dict)
    extra_includes = collections.defaultdict(set)   # header owner -> hand-made headers it needs
    problems = []

    def add(o, n, kind, decl, notes):
        entries[o][n] = (kind, decl, notes)

    # 1. functions defined in translated files and used by another file
    words = {rel: set(re.findall(r"\b\w+\b", " ".join(c for l, c in code_lines(read(rel)))))
             for rel in parsed}
    dr_words = set(re.findall(r"\b\w+\b", read("dr_types.h")))
    fixed_types = {}            # typedef name -> hand-made header defining it
    for h in FIXED_HEADERS - {"dr_types.h"}:
        for m in re.finditer(r"\}\s*(\w+)\s*;|typedef[^;{]*?\b(\w+)\s*;", read(h) or ""):
            fixed_types.setdefault(m.group(1) or m.group(2), h)
    for n, (rel, sig) in fdefs.items():
        if n in fixed or n == "WinMain":
            continue
        if not any(n in w for r, w in words.items() if r != rel):
            continue
        ids = set(re.findall(r"\b\w+\b", sig))
        used = ids & (parsed[rel][3] - dr_words)
        if used:
            problems.append("%s (%s): uses %s defined only in %s - not declared in a header" % (n, rel, ", ".join(sorted(used)), rel))
            continue
        for t in ids & set(fixed_types):
            extra_includes[rel].add(fixed_types[t])
        add(rel, n, "func", sig, existing.get(n, (None, []))[1])

    # 2. hand-written externs: functions not defined (stubs) and globals
    ext_by_name = collections.defaultdict(list)
    for rel, (defs, statics, externs, typedefs) in parsed.items():
        text_lines = read(rel).split("\n")
        for start, end, n, is_func, body in externs:
            if kept(text_lines, start):
                continue
            notes = []
            k = start - 1
            while k >= 0 and text_lines[k].startswith("// NOTE:"):
                notes.insert(0, text_lines[k])
                k -= 1
            trail = re.search(r";\s*(//.*)$", text_lines[end - 1])
            if trail and "NOTE" in trail.group(1):
                notes.append(trail.group(1))
            ext_by_name[n].append((rel, is_func, body, notes))

    for n, uses in ext_by_name.items():
        if n in fixed:
            continue
        rel0, is_func, body, notes = uses[0]
        allnotes = []
        for u in uses:
            for x in u[3]:
                if x not in allnotes:
                    allnotes.append(x)
        if is_func:
            if n in fdefs:
                continue
            o = func_folder.get(n)
            if not o:
                problems.append("%s: extern in %s, no IDA function of that name - left in place" % (n, ", ".join(u[0] for u in uses)))
                continue
            bodies = set(" ".join(u[2].split()) for u in uses)
            if len(bodies) > 1:
                problems.append("%s: different extern declarations: %s" % (n, " | ".join(sorted(bodies))))
            decl = existing.get(n, (body,))[0] if n in existing else body
            add(o, n, "stub", decl, existing.get(n, (None, allnotes))[1] or allnotes)
        else:
            if n not in g:
                problems.append("%s: extern in %s, not an IDA global - left in place" % (n, ", ".join(u[0] for u in uses)))
                continue
            entries[owner[n]].setdefault(n, None)
            pending_notes = allnotes
            entries[owner[n]][n] = ("data", None, existing.get(n, (None, pending_notes))[1] or pending_notes)

    # 3. globals defined in translated files and used elsewhere
    for n in g:
        o = owner[n]
        if n in fixed or n not in gdefs:
            continue
        if g[n][4] - {o}:
            if n not in entries[o]:
                entries[o][n] = ("data", None, existing.get(n, (None, []))[1])

    # 4. keep what the generated blocks already declare while a .c still uses it (the hand-written
    #    externs it came from are gone after the first run)
    produced = set(n for es in entries.values() for n in es)
    for n, h in existing_in.items():
        if n in produced or n in fixed or not any(n in w for w in words.values()):
            continue
        body, notes = existing[n]
        name, is_func = decl_name(body)
        if is_func and n in fdefs:
            continue            # defined now, but no other file uses it
        if h == "dr_globals.h":
            o = SHARED_OWNER
        else:
            d, b = os.path.split(h[:-2] + ".c")
            if b.startswith("dr_") and b[3:-2] + ".h" in CRT_HEADERS:
                b = b[3:]
            o = os.path.join(d, b).replace("\\", "/")
        if is_func:
            add(o, n, "stub", body, notes)
        elif n in g:
            entries[o][n] = ("data", None, notes)
        else:
            problems.append("%s: in %s but not an IDA global - dropped" % (n, h))

    # declaration text of globals
    macro_dim = re.compile(r"\[[^\]]*[A-Za-z_][^\]]*\]")
    for o, es in entries.items():
        for n, (kind, decl, notes) in list(es.items()):
            if kind != "data":
                continue
            cand = []
            if n in gdefs:
                d = sorted(gdefs[n])[0]
                m = re.search(r"^(?!extern|static|typedef)([A-Za-z_][\w \t\*]*?\b%s\b\s*(?:\[[^\]]*\]\s*)*)(?:=|;)" % n, read(d), re.M)
                if m:
                    cand.append(" ".join(m.group(1).split()))
            if n in existing:
                cand.append(existing[n][0])
            for u in ext_by_name.get(n, []):
                cand.append(" ".join(u[2].split()))
            decl = next((c for c in cand if not macro_dim.search(c)), None)
            if decl is None:
                a, size, idecl, mark, folders, refs = g[n]
                decl = P.c_decl(idecl, n, size).split(";")[0]
            notes = list(notes)
            mark = g[n][3]
            if (";extern" in mark or ";unused" in mark) and not any("IDA mark" in x for x in notes):
                notes.insert(0, "// NOTE: IDA mark %s" % mark)
            if o == SHARED_OWNER and not any("most references" in x for x in notes):
                notes.insert(0, "// most references: %s" % ", ".join("%s %d" % fc for fc in g[n][5].most_common(3)))
            es[n] = ("data", decl, notes)

    # write headers
    header_names = {}
    for o in sorted(entries):
        es = entries[o]
        if not es:
            continue
        h = "dr_globals.h" if o == SHARED_OWNER else header_of(o)
        header_names[o] = h
        guard = re.sub(r"\W", "_", h).upper()
        old = read(h)
        head, gen, tail = split_header(old)
        if gen is None:
            # new header, or one written before the markers: keep only what is not regenerated
            keep = []
            if old:
                for n, (body, notes) in header_decls(old).items():
                    if n not in es:
                        keep.extend(notes + ["extern %s;" % body, ""])
            if o == SHARED_OWNER:
                desc = ["/*", " * dr_globals.h - [A] globals whose owner file is not known yet", " *",
                        " * Not an original file: globals in the linker's common area with several users and no IDA",
                        " * @file mark (tools/progress.py --globals). Move each to its owner's header once known.", " */"]
            else:
                desc = ["/*", " * %s - globals and functions of %s used by other files" % (h, o), " *",
                        " * The block between the GENERATED markers is maintained by tools/headers.py; add",
                        " * hand-written declarations outside it."]
                if o not in translated:
                    desc.append(" * %s is not translated yet: only what translated code uses so far." % o)
                desc.append(" */")
            head = "\n".join(desc + ["", "#ifndef %s" % guard, "#define %s" % guard, "", '#include "dr_types.h"', "", ""])
            tail = "\n" + ("\n" + "\n".join(keep) if keep else "") + "\n#endif // %s\n" % guard
        body = []
        if extra_includes.get(o):
            body.append("")
            body.extend('#include "%s"' % x for x in sorted(extra_includes[o]))
        data = sorted((n for n in es if es[n][0] == "data"), key=lambda n: g[n][0])
        funcs = sorted(n for n in es if es[n][0] == "func")
        stubs = sorted(n for n in es if es[n][0] == "stub")
        for title, names in zip(SECTIONS, (data, funcs, stubs)):
            if not names:
                continue
            body.append("")
            body.append("// %s" % title)
            for n in names:
                kind, decl, notes = es[n]
                body.extend(notes)
                body.append("extern %s;" % decl)
        new = head + BEGIN + "\n".join(body) + "\n" + END + tail
        if new != old:
            print("%s %s (%d globals, %d functions, %d stubs)" % ("update" if old else "create", h, len(data), len(funcs), len(stubs)))
            write(h, new)

    declared = dict(fixed_in)
    declared.update(hand)
    hand = set(hand) | set(fixed_in)    # their externs in .c files are replaced too
    for o, es in entries.items():
        for n in es:
            declared[n] = header_names[o]

    # sources: drop externs now in headers, include the headers
    for rel, (defs, statics, externs, typedefs) in sorted(parsed.items()):
        if rel not in translated and not externs:
            continue        # an empty placeholder file
        text = read(rel)
        lines = text.split("\n")
        drop, includes = set(), set()
        for start, end, n, is_func, body in externs:
            if n in declared and (n not in fixed or n in hand):
                if is_func and n in statics:
                    continue
                if kept(lines, start):
                    continue
                drop.update(range(start, end))
                k = start - 1
                while k >= 0 and lines[k].startswith("// NOTE:"):
                    drop.add(k)
                    k -= 1
                includes.add(declared[n])
        own = header_names.get(rel)
        if own:
            includes.add(own)
        out = [l for i, l in enumerate(lines) if i not in drop]
        # section comments left with nothing under them
        res = []
        for i, l in enumerate(out):
            if re.match(r"^/\*[^*].*\*/$", l) and (i + 1 >= len(out) or not out[i + 1].strip()):
                continue
            res.append(l)
        out = res
        missing = [h for h in sorted(includes, key=str.lower)
                   if not re.search(r'^#include "(?:\.\./)*%s"' % re.escape(h), text, re.M)]
        if missing:
            idx = [i for i, l in enumerate(out) if l.startswith('#include "')] or \
                  [i for i, l in enumerate(out) if l.startswith("#include")]
            if idx:
                pos = idx[-1] + 1
                ins = ['#include "%s"' % h for h in missing]
                if not out[idx[-1]].startswith('#include "'):
                    ins.insert(0, "")
            else:
                pos = next((i + 1 for i, l in enumerate(out) if l.strip() == "*/"), 0)
                ins = [""] + ['#include "%s"' % h for h in missing]
            out[pos:pos] = ins
        new = re.sub(r"\n{3,}", "\n\n", "\n".join(out))
        if new != text:
            print("update %s (-%d extern lines, +%d includes)" % (rel, len(drop), len(missing)))
            write(rel, new)

    for p in problems:
        print("note:", p)


if __name__ == "__main__":
    main()
