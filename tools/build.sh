#!/bin/bash
# Full rebuild with regenerated stubs:
#   empty stubs.c -> build -> collect unresolved symbols -> gen_stubs.py (IDA) -> build again.
# Usage: tools/build.sh <work dir for logs> [Debug|Release]
# Needs the IDA database open (ida-mcp) for gen_stubs.py.
set -e
WORK="$1"
CONFIG="${2:-Debug}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/src_rebuild"
WIN_SRC="$(cygpath -w "$SRC")"
WIN_WORK="$(cygpath -w "$WORK")"

mkdir -p "$WORK"
printf '/* empty: regenerated by tools/build.sh */\n' > "$SRC/stubs/stubs.c"

cmd //c "$WIN_SRC\\build_vc2022.bat" "$CONFIG" > "$WORK/build_pass1.txt" 2>&1 || true
python "$ROOT/tools/build_errors.py" "$WORK/build_pass1.txt" "$WORK/unresolved.txt" > "$WORK/errors_pass1.txt"
if grep -q "^==" "$WORK/errors_pass1.txt"; then
    echo "compile errors:"; cat "$WORK/errors_pass1.txt"; exit 1
fi

(cd "$ROOT/tools/ida" && timeout 300 python idacall.py py gen_stubs.py SYMS="$WIN_WORK\\unresolved.txt" OUT="$WIN_SRC\\stubs\\stubs.c")

cmd //c "$WIN_SRC\\build_vc2022.bat" "$CONFIG" > "$WORK/build_pass2.txt" 2>&1 || true
python "$ROOT/tools/build_errors.py" "$WORK/build_pass2.txt" > "$WORK/errors_pass2.txt"
cat "$WORK/errors_pass2.txt" | head -40
grep -E "Driver\.exe$|-> .*Driver\.exe|fatal error" "$WORK/build_pass2.txt" || true
