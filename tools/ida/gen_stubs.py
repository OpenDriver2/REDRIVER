# IDAPython script, run through idacall.py:
#   python idacall.py py gen_stubs.py SYMS=<file with linker symbols, one per line> OUT=<stubs .c>
#
# Writes C definitions for symbols the rebuilt code references but does not define yet:
#   functions -> empty body that logs once and returns 0 (return type from IDA: void/int/float/double)
#   data      -> object with the IDA item size; initialised data gets its bytes from the database,
#                pointer slots become string literals (for strings) or 0 with a comment
import ida_name, ida_funcs, ida_bytes, ida_nalt, ida_typeinf, ida_segment, idautils, idc

SYMS = globals()["SYMS"]
OUT = globals()["OUT"]

# symbols that are not IDA items (inlined macros etc.) and must be written by hand
MANUAL = {"float_to_int"}


def find(cname):
    for n in (cname, "_" + cname):
        ea = ida_name.get_name_ea(idc.BADADDR, n)
        if ea != idc.BADADDR:
            return ea
    # file statics are named "file._name" in IDA
    for ea, n in idautils.Names():
        if n.endswith("._" + cname):
            return ea
    return idc.BADADDR


def ret_type(ea):
    t = ida_typeinf.tinfo_t()
    if not ida_nalt.get_tinfo(t, ea):
        return "int"
    fd = ida_typeinf.func_type_data_t()
    if not t.get_func_details(fd):
        return "int"
    r = fd.rettype
    if r.is_void():
        return "void"
    if r.is_floating():
        return "double" if r.get_size() == 8 else "float"
    return "int"


def c_string(b):
    out = '"'
    for c in b:
        out += chr(c) if 32 <= c < 127 and chr(c) not in '"\\' else "\\%03o" % c
    return out + '"'


def data_def(cname, ea):
    size = ida_bytes.get_item_size(ea)
    t = ida_typeinf.tinfo_t()
    if ida_nalt.get_tinfo(t, ea) and t.get_size() not in (0, idc.BADADDR) and t.get_size() > size:
        size = t.get_size()
    # IDA arrays are often typed too short (e.g. DISPLAY_MODE[] with one element): extend up to the
    # next item that has a name or is referenced
    nxt = ea + size
    end = min(ea + 0x10000, ida_segment.getseg(ea).end_ea)
    while nxt < end and not ida_name.get_name(nxt) and not any(True for _ in idautils.XrefsTo(nxt)):
        nxt = ida_bytes.next_head(nxt, end) if ida_bytes.next_head(nxt, end) != idc.BADADDR else end
    if nxt > ea + size and ida_bytes.is_loaded(ea):		# initialised data only; bss gaps are just padding
        size = nxt - ea
    seg = ida_segment.get_segm_name(ida_segment.getseg(ea))
    note = "IDA %s %s, %s, %d bytes" % (hex(ea), ida_name.get_name(ea), seg, size)
    if not ida_bytes.is_loaded(ea) or not any(ida_bytes.get_bytes(ea, size) or b""):
        return "// %s\nunsigned char %s[%d];\n" % (note, cname, size)
    # pointer slots: the dword holds the address of the item it references (enum/offset-type
    # references that are not real pointers are skipped)
    refs = {}
    for off in range(0, size - 3, 4):
        for x in idautils.DataRefsFrom(ea + off):
            if ida_bytes.get_dword(ea + off) == x and ida_segment.getseg(x):
                refs[off] = x
    if size % 4 == 0:
        words = []
        for off in range(0, size, 4):
            if off in refs:
                tgt = refs[off]
                if ida_bytes.is_strlit(ida_bytes.get_flags(tgt)):
                    s = ida_bytes.get_strlit_contents(tgt, -1, ida_nalt.STRTYPE_C) or b""
                    words.append("(unsigned int)%s" % c_string(s))
                else:
                    words.append("0 /* -> %s */" % (ida_name.get_name(tgt) or hex(tgt)))
            else:
                words.append(hex(ida_bytes.get_dword(ea + off)))
        return "// %s\nunsigned int %s[%d] = { %s };\n" % (note, cname, size // 4, ", ".join(words))
    raw = ida_bytes.get_bytes(ea, size)
    return "// %s\nunsigned char %s[%d] = { %s };\n" % (note, cname, size, ", ".join(hex(b) for b in raw))


lines = [
    "/*",
    " * stubs.c - GENERATED by tools/ida/gen_stubs.py, do not edit.",
    " * Definitions for everything the rebuilt code references but does not implement yet.",
    " * Functions log their first call (stubs.log) and return 0; data comes from the IDA database.",
    " */",
    "",
    '#include "stubs.h"',
    "",
]
funcs, data, missing = [], [], []
for sym in [l.strip() for l in open(SYMS) if l.strip()]:
    cname = sym[1:] if sym.startswith("_") else sym
    # __stdcall symbols are decorated with the argument size: _name@N
    argbytes = int(cname.split("@")[1]) if "@" in cname else None
    cname = cname.split("@")[0]
    if cname in MANUAL:
        continue
    ea = find(cname)
    if ea == idc.BADADDR:
        missing.append(cname)
        continue
    fn = ida_funcs.get_func(ea)
    if fn and fn.start_ea == ea:
        r = ret_type(ea)
        body = "STUB();" + ("" if r == "void" else " return 0;")
        if argbytes is None:
            funcs.append("%s %s() { %s }\t// IDA %s %s" % (r, cname, body, hex(ea), ida_name.get_name(ea)))
        else:
            args = ", ".join("int a%d" % i for i in range(argbytes // 4)) or "void"
            funcs.append("%s __stdcall %s(%s) { %s }\t// IDA %s %s" % (r, cname, args, body, hex(ea), ida_name.get_name(ea)))
    else:
        data.append(data_def(cname, ea))

lines.append("//------------------------------------------------------------------------------------------")
lines.append("// functions")
lines.append("")
lines += funcs
lines.append("")
lines.append("//------------------------------------------------------------------------------------------")
lines.append("// data")
lines.append("")
lines += data
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote %s: %d functions, %d data" % (OUT, len(funcs), len(data)))
if missing:
    print("NOT FOUND in IDA (write by hand):", " ".join(missing))
